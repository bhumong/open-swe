"""Create private, ignored environment files for loopback Open SWE development."""

from __future__ import annotations

import argparse
import base64
import os
import secrets
import shutil
import subprocess
import sys
from pathlib import Path

from dotenv import dotenv_values

ROOT = Path(__file__).resolve().parent.parent
LANGFUSE_ENV = ROOT / "infra" / "langfuse" / ".env"
OPEN_SWE_ENV = ROOT / ".env"
OPEN_SWE_ENV_MARKER = "# Generated by scripts/setup_local_env.py"
LANGFUSE_ENV_MARKER = "# Generated by scripts/setup_local_env.py"


def _local_secrets() -> dict[str, str]:
    return {
        "NEXTAUTH_URL": "http://localhost:3030",
        "NEXTAUTH_SECRET": secrets.token_hex(32),
        "SALT": secrets.token_hex(32),
        "ENCRYPTION_KEY": secrets.token_hex(32),
        "POSTGRES_PASSWORD": secrets.token_hex(32),
        "CLICKHOUSE_PASSWORD": secrets.token_hex(32),
        "REDIS_AUTH": secrets.token_hex(32),
        "MINIO_ROOT_USER": "openswe",
        "MINIO_ROOT_PASSWORD": secrets.token_hex(32),
        "LANGFUSE_INIT_ORG_ID": "open-swe-local",
        "LANGFUSE_INIT_ORG_NAME": "Open SWE Local",
        "LANGFUSE_INIT_PROJECT_ID": "open-swe-local",
        "LANGFUSE_INIT_PROJECT_NAME": "Open SWE Local",
        "LANGFUSE_INIT_PROJECT_PUBLIC_KEY": f"pk-lf-{secrets.token_hex(24)}",
        "LANGFUSE_INIT_PROJECT_SECRET_KEY": f"sk-lf-{secrets.token_hex(32)}",
        "LANGFUSE_INIT_USER_EMAIL": "openswe-local@example.test",
        "LANGFUSE_INIT_USER_NAME": "Open SWE Developer",
        "LANGFUSE_INIT_USER_PASSWORD": secrets.token_hex(32),
    }


def _read_settings(path: Path) -> dict[str, str]:
    if not path.is_file():
        return {}
    return {key: value for key, value in dotenv_values(path).items() if value is not None}


def _write_private_file(path: Path, values: dict[str, str], marker: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    content = marker + "\n" + "".join(f"{key}={value}\n" for key, value in values.items())
    try:
        descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    except FileExistsError:
        raise RuntimeError(f"Refusing to overwrite existing local env file {path.name}") from None
    with os.fdopen(descriptor, "w", encoding="utf-8") as output:
        output.write(content)


def _github_login() -> str:
    if shutil.which("gh") is None:
        raise RuntimeError("GitHub CLI is required; install gh and run `gh auth login` first")
    result = subprocess.run(
        ["gh", "api", "user", "--jq", ".login"],
        capture_output=True,
        check=False,
        text=True,
    )
    login = result.stdout.strip()
    if result.returncode or not login or any(char.isspace() for char in login):
        raise RuntimeError("Could not read the signed-in GitHub user; run `gh auth login` first")
    return login


def _source_anthropic_key() -> str:
    configured_source = os.environ.get("OPEN_SWE_SOURCE_ENV")
    source = Path(configured_source).expanduser() if configured_source else ROOT.parent.parent / ".env"
    value = _read_settings(source).get("ANTHROPIC_API_KEY", "").strip()
    if not value:
        raise RuntimeError(
            "ANTHROPIC_API_KEY is empty in the source .env; set OPEN_SWE_SOURCE_ENV to its path"
        )
    return value


def _open_swe_settings(
    *,
    anthropic_key: str,
    github_login: str,
    langfuse_settings: dict[str, str],
    retained_langsmith_settings: dict[str, str],
) -> dict[str, str]:
    settings = {
        key: value
        for key, value in retained_langsmith_settings.items()
        if key.startswith("LANGSMITH_") and key != "LANGSMITH_TRACING"
    }
    settings.update(
        {
            "LANGFUSE_PUBLIC_KEY": langfuse_settings["LANGFUSE_INIT_PROJECT_PUBLIC_KEY"],
            "LANGFUSE_SECRET_KEY": langfuse_settings["LANGFUSE_INIT_PROJECT_SECRET_KEY"],
            "LANGFUSE_BASE_URL": "http://localhost:3030",
            "LANGFUSE_TRACING_ENVIRONMENT": "development",
            "LANGFUSE_PROJECT_NAME": "Open SWE Local",
            "LANGSMITH_TRACING": "false",
            "LANGCHAIN_TRACING_V2": "false",
            "ANTHROPIC_API_KEY": anthropic_key,
            "LLM_MODEL_ID": "anthropic:claude-haiku-5-5",
            "ALLOWED_GITHUB_USERS": github_login,
            "CONFIGURED_ADMINS": github_login,
            "DASHBOARD_JWT_SECRET": secrets.token_hex(32),
            "TOKEN_ENCRYPTION_KEY": base64.urlsafe_b64encode(secrets.token_bytes(32)).decode(),
            "SANDBOX_TYPE": "local",
            "LOCAL_SANDBOX_ROOT_DIR": str(Path.home() / "open-swe-local-workspace"),
        }
    )
    return settings


def setup(*, langfuse_only: bool = False) -> tuple[bool, bool]:
    if not langfuse_only and OPEN_SWE_ENV.exists():
        existing = OPEN_SWE_ENV.read_text(encoding="utf-8")
        if OPEN_SWE_ENV_MARKER not in existing:
            raise RuntimeError(
                "Open SWE .env already exists and was left untouched; merge the local settings manually"
            )
    if LANGFUSE_ENV.exists() and LANGFUSE_ENV_MARKER not in LANGFUSE_ENV.read_text(
        encoding="utf-8"
    ):
        raise RuntimeError(
            "infra/langfuse/.env already exists and was left untouched; review it before setup"
        )

    github_login = _github_login() if not langfuse_only and not OPEN_SWE_ENV.exists() else ""
    anthropic_key = _source_anthropic_key() if not langfuse_only and not OPEN_SWE_ENV.exists() else ""
    source_path = (
        Path(os.environ["OPEN_SWE_SOURCE_ENV"]).expanduser()
        if os.environ.get("OPEN_SWE_SOURCE_ENV")
        else ROOT.parent.parent / ".env"
    )
    retained_settings = _read_settings(source_path)

    create_langfuse_env = not LANGFUSE_ENV.exists()
    langfuse_settings = _local_secrets() if create_langfuse_env else _read_settings(LANGFUSE_ENV)
    required = {
        "LANGFUSE_INIT_PROJECT_PUBLIC_KEY",
        "LANGFUSE_INIT_PROJECT_SECRET_KEY",
        "LANGFUSE_INIT_USER_EMAIL",
        "LANGFUSE_INIT_USER_PASSWORD",
    }
    if not required.issubset(langfuse_settings):
        raise RuntimeError("infra/langfuse/.env is missing required local Langfuse initialization values")

    create_open_swe_env = not langfuse_only and not OPEN_SWE_ENV.exists()
    open_swe_settings = (
        _open_swe_settings(
            anthropic_key=anthropic_key,
            github_login=github_login,
            langfuse_settings=langfuse_settings,
            retained_langsmith_settings=retained_settings,
        )
        if create_open_swe_env
        else {}
    )

    if create_langfuse_env:
        _write_private_file(LANGFUSE_ENV, langfuse_settings, LANGFUSE_ENV_MARKER)
    if create_open_swe_env:
        _write_private_file(OPEN_SWE_ENV, open_swe_settings, OPEN_SWE_ENV_MARKER)
    return create_langfuse_env, create_open_swe_env


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--langfuse-only",
        action="store_true",
        help="create or reuse the Langfuse config without preparing Open SWE's .env",
    )
    args = parser.parse_args()
    try:
        created_langfuse, created_open_swe = setup(langfuse_only=args.langfuse_only)
    except (OSError, RuntimeError, KeyError) as exc:
        print(f"Local setup stopped: {exc}", file=sys.stderr)
        return 1
    print(
        "Local Langfuse configuration "
        f"{'created' if created_langfuse else 'reused'}; Open SWE configuration "
        f"{'created' if created_open_swe else 'left unchanged'}."
    )
    print("Credential values were not displayed.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
